struct FishSpawnEntry {
    u8 fishIndex, habitat, weight;
};

struct FishSpawnRow {
    FishSpawnEntry *entries;
    u8 numEntries;
};

extern "C" {
void Clock_GetDayMonth(void *p);
void Clock_GetMinuteHour(void *p);
extern void *gCommManager;
}

extern FishSpawnRow **sFishTablesByPeriod[14];

// (the period's entry of sFishTablesByPeriod: by element - the entries are pointers, wider than a u32 on 64-bit
// hosts)
#define FISH_PERIOD(i) ((u32 *)&sFishTablesByPeriod[i])
extern "C" u32 *FishTable_GetForDate(u32 id, s32 k) {
    if (id >= 1 && id <= 7) {
        return FISH_PERIOD(id - 1);
    }
    if (id == 8) {
        if (k == 0) return FISH_PERIOD(id - 1);
        if (k == 1) return FISH_PERIOD(id);
        return 0;
    }
    if (id == 9) {
        if (k == 0) return FISH_PERIOD(id);
        if (k == 1) return FISH_PERIOD(id + 1);
        return 0;
    }
    if (id >= 10 && id <= 12) {
        return FISH_PERIOD(id + 1);
    }
    return 0;
}

extern "C" s32 FishTable_Pick(u32 *out0, u32 *out1, s32 a, s32 b, s32 c) {
    s32 lim;
    s32 sum = 0;
    s32 res = -1;
    s32 off;
    s32 i;
    if (((CommManager *)(gCommManager))->isOnline()) {
        off = 3;
        lim = Random_GlobalBelow(0x60);
    } else {
        off = 0;
        lim = Random_GlobalBelow(0x64);
    }
    for (i = 0; i < sFishTablesByPeriod[b - 1][c][a].numEntries - off; i++) {
        sum += sFishTablesByPeriod[b - 1][c][a].entries[i].weight;
        if (sum > lim) {
            res = i;
            break;
        }
    }
    if (res != -1) {
        *out0 = sFishTablesByPeriod[b - 1][c][a].entries[res].fishIndex;
        *out1 = sFishTablesByPeriod[b - 1][c][a].entries[res].habitat;
        return 1;
    }
    return 0;
}

extern "C" s32 FishTable_PickNow(void *a, void *b, s32 c) {
    u8 buf[4];
    u32 e;
    u8 x, y;
    Clock_GetDayMonth(buf);
    x = buf[1];
    Clock_GetMinuteHour(&buf[2]);
    y = buf[3];
    e = FishTable_GetPeriod(x);
    return FishTable_Pick((u32 *)a, (u32 *)b, c, e, FishTable_GetHourSlot(y));
}

